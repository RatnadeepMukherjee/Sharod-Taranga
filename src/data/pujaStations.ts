export function getAtmosphereByTime(date: Date = new Date()): TimeOfDay {
  const hour = date.getHours();
  if (hour >= 4 && hour < 7) return 'dawn';
  if (hour >= 7 && hour < 17) return 'day';
  if (hour >= 17 && hour < 21) return 'dusk';
  return 'night';
}
